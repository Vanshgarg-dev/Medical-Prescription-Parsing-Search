def process_upload(file):
    """Process an uploaded prescription file through the full pipeline."""
    if file is None:
        return "No file uploaded.", "", "", ""

    file_path = file.name if hasattr(file, "name") else file

    logs = []

    # Step 1: Upload to Supabase
    logs.append("⏳ [1/6] Uploading to Supabase Storage...")
    try:
        sb_result = upload_file(file_path)
        storage_url = sb_result["public_url"]
        logs.append(f"✅ Uploaded: {storage_url}")
    except Exception as e:
        logs.append(f"❌ Upload failed: {e}")
        return "\n".join(logs), "", "", ""

    # Step 2: Extract text
    logs.append("⏳ [2/6] Extracting text (OCR)...")
    try:
        extraction = extract_from_file(file_path)
        raw_text = extraction["text"]
        logs.append(f"✅ Extracted {len(raw_text)} chars (source: {extraction['source']})")
    except Exception as e:
        logs.append(f"❌ Extraction failed: {e}")
        return "\n".join(logs), "", "", ""

    if not raw_text.strip():
        logs.append("⚠️ No text extracted — file may be empty or unreadable.")
        return "\n".join(logs), "", "", ""

    # Step 3: Parse with LLM
    logs.append("⏳ [3/6] Parsing with Groq LLM...")
    try:
        parsed = parse_prescription(raw_text)
        if "error" in parsed:
            logs.append(f"❌ Parsing failed: {parsed['error']}")
            return "\n".join(logs), raw_text, "", ""
        logs.append("✅ Entities parsed successfully")
    except Exception as e:
        logs.append(f"❌ LLM error: {e}")
        return "\n".join(logs), raw_text, "", ""

    # Step 4: Store in DB
    logs.append("⏳ [4/6] Storing in PostgreSQL...")
    try:
        prescription_id = insert_prescription(
            file_name=sb_result["file_name"],
            storage_url=storage_url,
            file_type=sb_result["file_type"],
            raw_text=raw_text,
        )
        entity_id = insert_medical_entities(prescription_id, parsed)
        medications = parsed.get("medications", [])
        med_ids = insert_medications(entity_id, medications) if medications else []
        logs.append(f"✅ Stored — Prescription #{prescription_id}, {len(med_ids)} medications")
    except Exception as e:
        logs.append(f"❌ DB error: {e}")
        return "\n".join(logs), raw_text, json.dumps(parsed, indent=2, default=str), ""

    # Steps 5+6: Auto-generated by DB triggers
    logs.append("⏳ [5/6] Summary auto-generated by DB trigger...")
    ai_summary = get_prescription_summary(prescription_id)
    if ai_summary:
        logs.append(f"✅ Summary: {ai_summary[:100]}..." if len(ai_summary) > 100 else f"✅ Summary: {ai_summary}")
    else:
        logs.append("⚠️ Summary not generated (rate-limited — will retry on next access)")
    logs.append("✅ [6/6] Embedding auto-generated by DB trigger")

    logs.append("\n🎉 Pipeline complete!")

    # Build summary card
    summary = _build_summary(parsed, prescription_id, storage_url, ai_summary)

    return (
        "\n".join(logs),
        raw_text,
        json.dumps(parsed, indent=2, default=str),
        summary,
    )


def _build_summary(parsed: dict, rx_id: int, url: str, ai_summary: str = "") -> str:
    """Build a markdown summary of parsed prescription."""
    lines = [f"### Prescription #{rx_id}\n"]

    if parsed.get("patient_name"):
        lines.append(f"**Patient:** {parsed['patient_name']}")
    if parsed.get("patient_age"):
        lines.append(f"**Age:** {parsed['patient_age']}")
    if parsed.get("patient_gender"):
        lines.append(f"**Gender:** {parsed['patient_gender']}")
    if parsed.get("doctor_name"):
        lines.append(f"**Doctor:** {parsed['doctor_name']}")
    if parsed.get("doctor_speciality"):
        lines.append(f"**Speciality:** {parsed['doctor_speciality']}")
    if parsed.get("hospital_clinic"):
        lines.append(f"**Hospital:** {parsed['hospital_clinic']}")

    if parsed.get("diagnosis"):
        lines.append(f"\n**Diagnosis:** {', '.join(parsed['diagnosis'])}")
    if parsed.get("symptoms"):
        lines.append(f"**Symptoms:** {', '.join(parsed['symptoms'])}")

    meds = parsed.get("medications", [])
    if meds:
        lines.append(f"\n**Medications ({len(meds)}):**\n")
        lines.append("| # | Drug | Dosage | Frequency | Duration | Route | Instructions |")
        lines.append("|---|------|--------|-----------|----------|-------|-------------|")
        for i, m in enumerate(meds, 1):
            lines.append(
                f"| {i} | {m.get('drug_name', '-')} | {m.get('dosage') or '-'} | "
                f"{m.get('frequency') or '-'} | {m.get('duration') or '-'} | "
                f"{m.get('route') or '-'} | {m.get('instructions') or '-'} |"
            )

    if ai_summary:
        lines.append(f"\n**AI Summary:** {ai_summary}")

    lines.append(f"\n[View file]({url})")
    return "\n".join(lines)


