def search_prescriptions(query: str, search_type: str) -> str:
    """Search prescriptions by various methods."""
    if not query.strip():
        return "Please enter a search query."

    try:
        if search_type == "Natural Language (AI)":
            sql = semantic_search_query(query)
            if sql.startswith("```"):
                lines = sql.split("\n")
                sql = "\n".join(lines[1:-1]) if lines[-1].strip() == "```" else "\n".join(lines[1:])
            sql = sql.strip().rstrip(";")
            results = execute_raw_query(sql)
            header = f"**Generated SQL:**\n```sql\n{sql}\n```\n\n"
        elif search_type == "Drug Name":
            results = search_by_drug(query)
            header = ""
        elif search_type == "Patient Name":
            results = search_by_patient(query)
            header = ""
        elif search_type == "Diagnosis":
            results = search_by_diagnosis(query)
            header = ""
        elif search_type == "Full Text":
            results = search_fulltext(query)
            header = ""
        elif search_type == "Semantic (Vector)":
            results = semantic_search(query)
            header = "**Semantic search** — matching by meaning against prescription summaries\n\n"
        else:
            return "Unknown search type."

        if not results:
            return header + "No results found."

        return header + f"**Found {len(results)} result(s):**\n\n```json\n{json.dumps(results, indent=2, default=str)}\n```"

    except Exception as e:
        return f"❌ Search error: {e}"


def get_prescription_detail(rx_id: str) -> str:
    """Get full details of a prescription by ID."""
    if not rx_id.strip():
        return "Enter a prescription ID."
    try:
        result = get_prescription_by_id(int(rx_id))
        if not result:
            return "Prescription not found."
        return f"```json\n{json.dumps(result, indent=2, default=str)}\n```"
    except Exception as e:
        return f"❌ Error: {e}"


def get_db_schema() -> str:
    """Return the live database schema."""
    try:
        schema = introspect_schema()
        return f"```\n{schema}\n```"
    except Exception as e:
        return f"❌ Error: {e}"


